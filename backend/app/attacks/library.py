DEFAULT_CATEGORIES: list[str] = sorted({a["category"] for a in ATTACK_LIBRARY})


def build_attack_library(attack_categories: list[str] | None = None) -> list[dict[str, Any]]:
    """Return base attacks filtered by category if provided."""
    if not attack_categories:
        return list(ATTACK_LIBRARY)
    wanted = set(attack_categories)
    return [a for a in ATTACK_LIBRARY if a["category"] in wanted]


def get_attack_by_id(attack_id: str) -> dict[str, Any] | None:
    for a in ATTACK_LIBRARY:
        if a["id"] == attack_id:
            return a
    return None